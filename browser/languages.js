const streams={rb:ruby,rake:ruby,gemspec:ruby,go,rs:rust,c,h:c,cc:cpp,cpp,cxx:cpp,hpp:cpp,hxx:cpp,java,cs:csharp,kt:kotlin,kts:kotlin,scala,dart,m:objectiveC,swift,yml:yaml,yaml,toml,sh:shell,bash:shell,zsh:shell,fish:shell,xml,svg:xml,xsl:xml,lua,pl:perl,pm:perl,r,ps1:powerShell,clj:clojure,cljs:clojure,cljc:clojure,scss:sass,sass,ini:properties,properties,glsl:shader,vert:shader,frag:shader};
const cached=new Map();
export function languageForPath(path=''){
 const name=path.split('/').at(-1),ext=name.includes('.')?name.split('.').at(-1).toLowerCase():'';
 const key=/^(Gemfile|Rakefile|Guardfile|Brewfile|Vagrantfile)$/.test(name)?'rb':/^Dockerfile(?:\.|$)/i.test(name)?'dockerfile':name==='.bashrc'||name==='.zshrc'?'sh':ext;
 if(cached.has(key))return cached.get(key);
 let support;
 if(/^[cm]?[jt]sx?$/.test(key))support=javascript({typescript:/tsx?$/.test(key),jsx:/[jt]sx$/.test(key)});
 else if(key==='py'||key==='pyi')support=python();
 else if(['json','jsonc','ipynb'].includes(key))support=json();
 else if(['html','htm','erb'].includes(key))support=html();
 else if(key==='css')support=css();
 else if(key==='sql')support=sql();
 else if(['php','phtml'].includes(key))support=php();
 else if(['md','markdown','mdx'].includes(key))support=markdown();
 else if(key==='dockerfile')support=StreamLanguage.define(dockerFile);
 else if(streams[key])support=StreamLanguage.define(streams[key]);
 else return null;
 cached.set(key,support);return support;
}
